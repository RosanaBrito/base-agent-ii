# 2. Loop passando mensagem por mensagem
for i, mensagem in enumerate(mensagens_paciente, 1):
    print(f"\n" + "-" * 30)
    print(f"Turno {i}")
    print(f"👤 Paciente: '{mensagem}'\n")
    print("🤖 --- Pensamento/Ações do Agente ---")

    # Injeta a mensagem do usuário
    inputs = {"messages": [("user", mensagem)]}

    # 3. Executa o stream PASSANDO O CONFIG para ativar a memória
    ultima_msg = None
    for step in agente_triagem.stream(inputs, config=config, stream_mode="updates"):
        for node_name, node_state in step.items():
            ultima_msg = node_state["messages"][-1]

            # Intercepta e exibe se o agente usou alguma ferramenta
            if hasattr(ultima_msg, "tool_calls") and ultima_msg.tool_calls:
                for tool_call in ultima_msg.tool_calls:
                    print(f"🛠️  Chamou a ferramenta: {tool_call['name']}")
                    print(f"   Parâmetros: {tool_call['args']}")

    # Exibe a resposta que o agente gerou para o usuário neste turno
    print("\n💬 --- Resposta Final para o Paciente ---")
    if hasattr(ultima_msg, "content") and ultima_msg.content:
        if isinstance(ultima_msg.content, list):
            for item in ultima_msg.content:
                if isinstance(item, dict) and item.get("type") == "text":
                    print(item.get("text", ""))
        else:
            print(ultima_msg.content)

    # Pausa entre as mensagens para simular a digitação e evitar Rate Limit
    if i < len(mensagens_paciente):
        print("\n⏳ Aguardando próxima mensagem do usuário...")
